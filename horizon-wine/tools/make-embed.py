#!/usr/bin/env python3
"""Turn binary files into one C or assembly file of arrays, for what the runtime
carries inside itself: the homebrew loader, icons, and Carafe's menu and fonts."""
import pathlib
import sys


def write_c(out, pairs):
    lines = ["/* Generated by tools/make-embed.py. Do not edit. */",
             "#include <stddef.h>", ""]
    for name, path in pairs:
        data = pathlib.Path(path).read_bytes()
        lines.append("const unsigned char %s[] = {" % name)
        for i in range(0, len(data), 16):
            lines.append("    " + "".join("0x%02x," % b for b in data[i:i + 16]))
        lines.append("};")
        lines.append("const size_t %s_size = sizeof(%s);" % (name, name))
        lines.append("")
    out.write_text("\n".join(lines))


def write_asm(out, pairs):
    lines = ["/* Generated by tools/make-embed.py --asm. Do not edit. */", ""]
    for name, path in pairs:
        abs_path = str(pathlib.Path(path).resolve()).replace("\\", "\\\\").replace('"', '\\"')
        lines.extend([
            f'.section .rodata.{name},"a",%progbits',
            ".balign 8",
            f".global {name}",
            f".type {name}, %object",
            f"{name}:",
            f'.incbin "{abs_path}"',
            f".L_{name}_end:",
            f".size {name}, .L_{name}_end - {name}",
            ".balign 8",
            f".global {name}_size",
            f".type {name}_size, %object",
            f"{name}_size:",
            f".quad .L_{name}_end - {name}",
            f".size {name}_size, 8",
            "",
        ])
    out.write_text("\n".join(lines))


def main(argv):
    asm = False
    args = argv[1:]
    if args and args[0] == "--asm":
        asm = True
        args = args[1:]
    out = pathlib.Path(args[0])
    pairs = list(zip(args[1::2], args[2::2]))
    if asm:
        write_asm(out, pairs)
    else:
        write_c(out, pairs)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
