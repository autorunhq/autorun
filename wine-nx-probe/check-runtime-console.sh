"${CC:-clang}" $flags "$root/wine-nx-probe/tests/std_stream_lines.c" -o "$build/std_stream_lines"
"$build/std_stream_lines"
"${CC:-clang}" $flags -I"$root/include" "$root/wine-nx-probe/tests/horizon_file_access.c" -o "$build/file_access"
"$build/file_access"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/pointer_cursor.c" -o "$build/pointer_cursor"
"$build/pointer_cursor"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_message_queue.c" -o "$build/message_queue"
"$build/message_queue"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_win_timers.c" -o "$build/win_timers"
"$build/win_timers"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_msg_queue.c" -o "$build/msg_queue"
"$build/msg_queue"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_clipboard.c" -o "$build/clipboard"
"$build/clipboard"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/launcher_list.c" -o "$build/launcher_list"
"$build/launcher_list"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/launcher_settings.c" -o "$build/launcher_settings"
"$build/launcher_settings"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/launcher_pe.c" -o "$build/launcher_pe"
"$build/launcher_pe" "$root/wine-nx-probe/build-switch-wow64-dynarec/switch/wine/drive_c"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/sd_read_cache.c" -o "$build/sd_read_cache"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/sd_write_buffer.c" -o "$build/sd_write_buffer"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/sd_stat_cache.c" -o "$build/sd_stat_cache"
"$build/sd_stat_cache"
"$build/sd_write_buffer"
"$build/sd_read_cache"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/box64_code_arena.c" -o "$build/box64_code_arena"
"$build/box64_code_arena"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_registry.c" -o "$build/registry"
"$build/registry"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/registry_paths.c" -o "$build/registry_paths"
"$build/registry_paths"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_read_redirect.c" -o "$build/read_redirect"
"$build/read_redirect"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_object_dirs.c" -o "$build/object_dirs"
"$build/object_dirs"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_keyboard.c" -o "$build/keyboard"
"$build/keyboard"
"${CC:-clang}" $flags -D__WINESRC__ -DWINE_UNIX_LIB -D_WIN64 -I"$root/include" "$root/wine-nx-probe/tests/horizon_completion.c" -o "$build/completion"
"$build/completion"
"${CC:-clang}" $flags "$root/wine-nx-probe/tests/horizon_free_range.c" -o "$build/free_range"
"$build/free_range"
python3 "$root/wine-nx-probe/tests/check_horizon_va_search.py"
python3 "$root/wine-nx-probe/tests/check_horizon_guest_reserve.py"
python3 "$root/wine-nx-probe/tests/check_horizon_reservation_transition.py"
python3 "$root/wine-nx-probe/tests/check_horizon_reservation_bounds.py"
python3 "$root/wine-nx-probe/tests/check_commit_chunks.py"
python3 "$root/wine-nx-probe/tests/check_waitable_timer.py"
